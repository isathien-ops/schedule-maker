"""Предметный слой программы «Расписание занятий»: курсы, этапы, правила, варианты, файлы проекта.

Здесь вся логика расписания онлайн-школы; веб-сервер (src/web) только проверяет ввод, спрашивает
подтверждения и сохраняет файлы. Модули ничего не знают о Flask и о странице. Устройство данных
проекта (settings, answer), разделы и этапы описаны в шапке model.py.

Модули
------
    модуль            за что отвечает
    model.py          данные проекта: разделы и этапы, курсы по имени, даты, уроки в расписании,
                      отметки времени преподавателей — простые функции для всех остальных
    files.py          чтение и атомарная запись JSON-файлов
    journal.py        журналы программы и сборок
    grid.py           сетка дня: время уроков, правка сетки и перенос уроков по новым номерам
    pairs.py          пары предметов «можно / нежелательно / нельзя» и пары курсов (одна линейка,
                      уровни ЕГЭ, «сдают вместе»)
    courses.py        курсы, разделы, линейки, нагрузка, преподаватель курса, идущие курсы,
                      закреплённые уроки и перенос уроков
    joint.py          «линейка идёт вместе с Потоком N»: курсы-копии, их источники, отметка
                      (setJointLine), синхронизация копий с источниками и помехи общих уроков
                      соседям в даты потока-копии (copyConflicts), общие уроки во время «не может»
                      (copyCannot)
    stages.py         этапы: список, даты, принятые и идущие курсы, «этап построен»,
                      занятость преподавателей
    penalties.py      свои правила пользователя: цены для решателя, подсчёт нарушений, описание,
                      ключи их строк в таблице вариантов
    school_defaults.py программа курсов, пары предметов и даты нового проекта
    solver_input.py   вход решателя для одного этапа (buildStageSettings) и прогноз, сколько
                      уроков он закрепит (pinForecast)
    variants.py       варианты этапа: файлы, встроенные правила (метрики и подписи к урокам),
                      причины нехватки уроков, порядок «лучший / ничья», кто ведёт курсы
                      варианта (lessonTeachers, teacherCourses) и сторож лимита курсов
                      (teacherOverLimit) — смена преподавателя в подборе
    staffing.py       «нужен ещё преподаватель»
    teacher_card.py   карточка преподавателя на вкладке «Преподаватели»
    export.py         книги Excel
    tree.py           папки проектов: создание и открытие (prepareProject), формат, архивы
    versions.py       сохранённые версии проекта

Слои
----
Импорт идёт только вниз: модуль может импортировать из предметного слоя только модули
с меньшим номером слоя, поэтому циклов импорта нет. Импортов внутри функций нет.
Правило проверяет tests/test_structure.py (DomainLayerTests); новый модуль добавляется
в таблицу здесь и в DOMAIN_LAYERS там.

    0  model, files, journal        — ничего из предметного слоя
    1  grid, pairs                  → model
    2  courses                      → model, grid, pairs
    3  joint                        → model, grid, pairs, courses
    4  stages, penalties,           → слои 0–3
       school_defaults
    5  solver_input                 → слои 0–4
    6  variants                     → слои 0–5
    7  staffing, teacher_card,      → слои 0–6
       export, tree, versions

Кроме предметного слоя, модули берут только src.variables (папки данных) и src.modules.translate
(тексты; penalties, variants и export — для подписей и подстановки в тексты).
"""
