"""Локальный веб-сервер приложения «Расписание занятий» для онлайн-школы.

Этот файл — точка сборки сервера и его публичный фасад: своей логики здесь нет. Он импортирует
все модули с маршрутами и действиями (при импорте они регистрируются в app и в реестре действий)
и отдаёт наружу несколько имён для web.py и тестов.

Как устроено приложение
-----------------------
* Страница (папка `static/`: index.html, app.css и скрипты страницы, порядок — в index.html) —
  «тонкий» клиент. Всё, что человек меняет на странице, приходит сюда JSON-запросом; сервер
  читает и записывает файлы проекта в PATH_TO_FOLDER/projects/<имя проекта>/ и возвращает
  странице её новое состояние.
* Само расписание строит отдельная программа `src/modules/solve.exe` (C++, метод имитации
  отжига). Сервер запускает её в фоновой нити, по одному этапу за раз и несколько раз
  подряд — так получаются «варианты», из которых человек выбирает и принимает один.
* Сервер запускается из `web.py` и обслуживает только 127.0.0.1, то есть открыт лишь
  на этом компьютере; паролей и пользователей нет.

Термины
-------
* Поток («Поток 1», «Поток 2», …) — курсы с общими датами начала и конца; в данных это
  `stream_id` (число). Блок — курсы без потока: доп. курсы, майские марафоны, летняя школа;
  ключ блока — слово ("extra", "may", "summer"). Поток или блок вместе зовутся section
  (раздел на вкладке «Курсы»).
* Линейка — группа курсов внутри потока или блока: в потоке (а также в майских марафонах и
  летней школе) это ОГЭ, ЕГЭ основной, ЕГЭ продвинутый, 10 класс, 8 класс; в доп. курсах —
  семинары («Семинар ОГЭ», «Семинар ЕГЭ продвинутый»).
* Этап (stage) — то, что строится за один запуск решателя: курсы одного потока или одного
  блока. Ключ этапа — номер потока строкой ("1") или имя блока (model.stageKey).
* «Курс уже идёт» (courseStarted) — дата начала наступила и у курса есть уроки в принятом
  расписании: его преподаватель и время больше не меняются.
* «Курс зафиксирован» (courseLocked) — курс идёт и все его уроки расставлены.
* Закреплённые уроки (pins) — день и время, которые человек сам назначил урокам курса.
* Режим keep («оставить принятое») — новая сборка этапа не трогает уже принятые уроки его
  курсов, решатель только дополняет недостающие.

API
---
* GET-маршруты отдают данные: тексты интерфейса и справочник (core.py), список проектов
  и состояние проекта (projects.py), карточку преподавателя (tabs/teachers.py), варианты
  этапа (tabs/preview.py), ход сборки (tabs/run.py), выгрузки в Excel / ZIP (tabs/export.py).
* Стартовый экран создаёт, импортирует, открывает и удаляет проекты своими маршрутами
  (projects.py).
* Все изменения открытого проекта идут через один маршрут POST /api/project/<p>/action;
  протокол (ответы confirm / notice / message, ошибки) — в шапке actions.py.

Модули
------
Файлы проекта (settings.json, answer.json, weights.json, варианты, версии) описаны в шапке
project.py. Предметная логика — в src/modules/functions/*.py (карта модулей и их слои — в шапке
src/modules/functions/__init__.py); сервер лишь проверяет ввод, спрашивает подтверждения,
сохраняет версию «Перед: …» и файлы.

    файл              за что отвечает                                         вкладка
    core.py           app, журнал, LOCK, UserError, ошибки, страница,         —
                      тексты, /api/meta
    project.py        папка и файлы проекта, версия «Перед: …», переписывание —
                      вариантов, проверка аргументов, формулировки
    build.py          фоновая сборка: solve.exe, задания JOBS, runJob,        —
                      startJob / stopJob / forget, ход сборки
    state.py          полное состояние проекта для страницы, сводки этапов    —
    ranking.py        варианты этапа с оценками: переставленные уроки,        preview, export
                      сдвиг общих уроков в потоках-копиях, смена
                      преподавателя, отклонённые варианты
    actions.py        реестр действий, @action, единый маршрут …/action       —
    projects.py       стартовый экран: список, создание, импорт,              стартовый экран
                      удаление, открытие
    tabs/settings.py  сетка времени, ограничение курсов, пары предметов       settings
    tabs/classes.py   потоки, даты, линейки, курсы, часы, преподаватель,      classes
                      закрепления, присоединение линейки
    tabs/teachers.py  преподаватели, доступность, карточка преподавателя      teachers
    tabs/run.py       веса, параметры, свои правила, запуск и остановка       run
    tabs/preview.py   варианты этапа, отклонение и принятие                   preview
    tabs/save.py      версии проекта                                          save
    tabs/export.py    скачивания: ZIP проекта и книги Excel                   export
    server.py         точка сборки (этот файл)                                —

Вкладка «Расписание» (view) своего модуля не имеет: её данные — в state(). Соответствие вкладок
серверу и страницы — в шапке tabs/__init__.py.

Слои: импорт идёт только вниз, циклов нет (проверяет tests/test_structure.py). Таблица
говорит, что модулю МОЖНО импортировать из src.web; фактически каждый берёт только нужное
(например, state и ranking сейчас core не импортируют):
    0  src/variables, src/modules/translate, src/modules/functions/*
    1  core      → ничего из src.web
    2  project   → может: core
    3  build     → может: core, project
    4  state     → может: core, project, build;   ranking → может: core, project
    5  actions   → может: core, build, state
    6  projects  → может: core, project, build, state
    7  tabs/*    → может: core, project, actions, state, ranking, build; никогда tabs.*,
                   projects, server
    8  server    → все (его импортируют только web.py и тесты)
Правила импорта:
* build — только `from src.web import build` и обращение build.SOLVER, build.JOBS…;
  `from src.web.build import …` запрещён: SOLVER подменяют тесты, а JOBS изменяемый.
* datetime — только `import datetime`: тесты подменяют datetime.date.
* Единственные app и LOCK — в core.py; маршруты регистрируются обычным @app.route в своих
  модулях (без Blueprint), имя функции-маршрута — endpoint Flask.
* Новый модуль с маршрутами или действиями добавляется в список импортов ниже вручную:
  PyInstaller находит модули только по статическим импортам.

Имена с подчёркиванием (одно правило для src и web.py)
------------------------------------------------------
Префикс «_» значит «внутренний шаг этого модуля»: другие модули программы его не импортируют
и не вызывают (тесты могут — им можно проверять шаги по отдельности). Он ставится в модулях-
службах с небольшим открытым набором функций и большим внутренним устройством: actions.py
(_outcome, _request) и build.py (шаги сборки runJob, структуры Windows). В остальных модулях
(вкладки, project, state, ranking, предметный слой) подчёркиваний нет: каждая функция там —
самостоятельный шаг, описанный в шапке модуля, и её можно брать из других модулей своего слоя.
Правило проверяет tests/test_structure.py (PrivateNameTests).
"""

