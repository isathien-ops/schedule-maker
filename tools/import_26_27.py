"""Импорт реальной таблицы школы в тестовый набор данных (fixture).

Собирает файл `tests/fixtures/school_26_27.json` из выгрузки Google-таблицы
«Расписание и программы 26/27» (файл .xlsx, скачанный из Google Sheets).

Запуск (из корня проекта):
    python tools/import_26_27.py <путь к выгруженному .xlsx>

Что читается:
- листы «Расписание 1 поток (для ОП)» и «Расписание 2 поток (для ОП)» — по одному на поток
  (поток — набор учеников, начинающих учиться в определённую дату);
- на каждом листе четыре блока колонок, по одному на линейку (ЕГЭ, 10 класс, ОГЭ, 8 класс),
  см. `BLOCKS`;
- каждая строка, где заполнены день и время, — это урок курса;
- строки с видом «домашка» пропускаются (это не урок в расписании);
- строки с видом «ДОП» — дополнительные курсы (семинары): они общие для всех потоков,
  поэтому попадают в курс без потока (`stream = None`) в линейку семинаров (`EXTRA_LINES`).

Результат — JSON со списком курсов: поток, линейка, предмет, недельные часы, учителя
и реальные слоты (день, номер урока) — то, как уроки стоят в таблице сейчас. Этот файл
читает `tools/school_26_27.py` (сборка настроек проекта), а через него — тесты
(`tests/fixture_26_27.py`, `tests/test_engine_programs.py`) и инструменты
`tools/create_test_project.py`, `tools/create_school_project.py`.

Основные точки входа: `parse(path)` — разбор книги; блок `__main__` — запись JSON.
"""

import collections
import json
import re
import sys
import warnings

import openpyxl

# Номер потока -> имя листа в книге. Внимание: у листа второго потока в таблице
# в конце имени стоит пробел — так он и называется, это не опечатка здесь.
SHEETS = {1: "Расписание 1 поток (для ОП)", 2: "Расписание 2 поток (для ОП) "}
# Дата начала занятий каждого потока
STARTS = {1: "2026-09-07", 2: "2026-11-23"}
# Дата начала дополнительных курсов (семинаров), общих для потоков
EXTRA_START = "2026-10-05"

# Сокращения дней недели из таблицы -> номер дня (0 = понедельник)
DAYS = {"ПН": 0, "ВТ": 1, "СР": 2, "ЧТ": 3, "ПТ": 4, "СБ": 5, "ВС": 6}

# Сетка уроков недели в том виде, как время записано в листах:
# GRID[день][номер урока] = "начало - конец". В будни 3 вечерних урока,
# в субботу 6, в воскресенье 2. Эта же сетка уходит в JSON как "day_grid".
GRID = [
    ["16:20 - 17:50", "18:00 - 19:30", "19:40 - 21:10"],
    ["16:20 - 17:50", "18:00 - 19:30", "19:40 - 21:10"],
    ["16:20 - 17:50", "18:00 - 19:30", "19:40 - 21:10"],
    ["16:20 - 17:50", "18:00 - 19:30", "19:40 - 21:10"],
    ["16:20 - 17:50", "18:00 - 19:30", "19:40 - 21:10"],
    ["10:00 - 11:30", "11:40 - 13:10", "13:20 - 14:50", "16:20 - 17:50", "18:00 - 19:30", "19:40 - 21:10"],
    ["10:00 - 11:30", "11:40 - 13:10"],
]

# Блоки колонок листа: пять букв колонок по порядку означают
# (предмет, день, время, вид урока, учитель), второй элемент — линейка блока.
# Блок «ЕГЭ» внутри делится подзаголовками на «ЕГЭ основной», «ЕГЭ продвинутый»
# и базовую математику (см. `egeLine`).
BLOCKS = [("ABCDE", "ЕГЭ"), ("GHIJK", "10 класс"), ("MNOPQ", "ОГЭ"), ("STUVW", "8 класс")]

# Распознавание предмета по началу текста ячейки (в таблице пишут по-разному:
# «Русский», «русский язык», «Матем. профиль» и т.п.): (префикс в нижнем регистре, имя предмета)
SUBJECTS = [
    ("русск", "Русский язык"), ("матем", "Математика"), ("биолог", "Биология"), ("информ", "Информатика"),
    ("физик", "Физика"), ("истор", "История"), ("литер", "Литература"), ("общест", "Обществознание"),
    ("хими", "Химия"), ("англ", "Английский язык"), ("геогр", "География"),
]

# Один и тот же человек записан в листах по-разному (опечатки, без имени):
# написание из таблицы -> единое имя учителя
TEACHERS = {
    "Коавчук Элина": "Кравчук Элина",
    "Сафиуллин Виталий": "Сафиулин Виталий",
    "Баранникова": "Баранникова Анна",
}

# В какую линейку семинаров попадает «ДОП»-урок в зависимости от блока, где он стоит.
# Всё, что не ОГЭ, считается семинаром ЕГЭ продвинутого (см. `parse`).
EXTRA_LINES = {"ЕГЭ продвинутый": "Семинар ЕГЭ продвинутый", "ОГЭ": "Семинар ОГЭ"}


def subjectOf(text):
    """Определяет предмет по тексту ячейки «предмет».

    Сравнивает начало текста (без пробелов по краям, в нижнем регистре) с префиксами
    из `SUBJECTS`. Возвращает имя предмета или `None`, если ячейка пуста или предмет
    не распознан (такие строки `parse` пропускает).
    """
    text = (text or "").strip().lower()

    return next((name for prefix, name in SUBJECTS if text.startswith(prefix)), None)


def egeLine(header):
    """Определяет линейку по подзаголовку внутри блока «ЕГЭ».

    Блок ЕГЭ в листе разбит подзаголовками вида «… (базовый)», «… (продвинутый)».
    Возвращает «ЕГЭ продвинутый», «ЕГЭ основной» или особую метку "base" для
    базовой математики — её `parse` потом превращает в предмет «Математика база»
    линейки «ЕГЭ основной».
    """
    header = header.lower()

    # Базовая математика — отдельный предмет «Математика база» линейки «ЕГЭ основной»;
    # здесь только ставим метку, пока ещё не прочитан сам предмет строки
    if "базов" in header:
        return "base"

    if "продвинут" in header:
        return "ЕГЭ продвинутый"

    return "ЕГЭ основной"


def teacherName(text):
    """Приводит имя учителя из ячейки к единому виду.

    Схлопывает лишние пробелы, исправляет известные разночтения по словарю `TEACHERS`.
    Возвращает имя или `None`, если ячейка пустая.
    """
    name = re.sub(r"\s+", " ", str(text or "")).strip()

    return TEACHERS.get(name, name) or None


def slotOf(day, time):
    """Переводит день и время из таблицы в слот сетки `[день, номер урока]`.

    `day` — номер дня (0 = понедельник), `time` — текст ячейки времени, например
    «18:00 - 19:30» или «18.00». Берётся только время начала и ищется урок сетки
    `GRID[day]`, который начинается в это время.

    Возвращает `None`, если в ячейке нет времени вообще. Если время есть, но такого
    урока в сетке этого дня нет, бросает `ValueError` — значит, таблица и сетка
    разошлись и импорт надо проверить вручную.
    """
    start = re.match(r"\s*(\d{1,2})[.:](\d{2})", str(time))

    if not start:
        return None

    # Нормализуем «9.30» -> «09:30», чтобы сравнивать с началом строк сетки
    start = f"{int(start.group(1)):02d}:{start.group(2)}"

    for lesson, value in enumerate(GRID[day]):
        if value.startswith(start):
            return [day, lesson]

    raise ValueError(f"no grid lesson starts at {start} on day {day}")


def parse(path):
    """Читает книгу .xlsx и возвращает данные для `school_26_27.json`.

    `path` — путь к выгрузке таблицы. Возвращает словарь:
    - "source" — откуда данные;
    - "day_grid" — сетка уроков `GRID`;
    - "streams" — {"1": дата начала, "2": дата начала};
    - "extra_start" — дата начала семинаров;
    - "courses" — список курсов: {"stream", "line", "subject", "slots", "teachers", "hours"}.
      "slots" — все различные слоты курса из таблицы, "hours" — уроков в неделю,
      "teachers" — учителя в порядке появления (первый считается основным, «ведёт»).

    Курс однозначно задаётся тройкой (поток, линейка, предмет); у семинаров поток `None`.
    """
    # openpyxl шумит предупреждениями о форматировании Google-выгрузки — они не важны
    warnings.filterwarnings("ignore")
    # data_only=True: берём вычисленные значения ячеек, а не формулы
    book = openpyxl.load_workbook(path, data_only=True)
    # Курсы в порядке первого появления в таблице, ключ — (поток, линейка, предмет)
    courses = collections.OrderedDict()

    def course(stream, line, subject):
        """Возвращает запись курса (поток, линейка, предмет), создавая пустую при первом обращении."""
        key = (stream, line, subject)
        return courses.setdefault(key, {"stream": stream, "line": line, "subject": subject, "slots": [], "teachers": []})

    for stream, sheet in SHEETS.items():
        ws = book[sheet]

        for columns, block in BLOCKS:
            # Текущая линейка; в блоке ЕГЭ она меняется на подзаголовках
            line = block

            # Данные начинаются с 6-й строки (выше — шапка листа)
            for row in range(6, ws.max_row + 1):
                subject_cell, day_cell, time_cell, kind_cell, teacher_cell = (ws[f"{column}{row}"].value for column in columns)

                # Подзаголовок блока ЕГЭ: текст со скобкой и без дня — переключает линейку
                if subject_cell and not day_cell and "(" in str(subject_cell) and block == "ЕГЭ":
                    line = egeLine(str(subject_cell))
                    continue

                day = DAYS.get(str(day_cell or "").strip().upper())
                time = str(time_cell or "").strip()
                kind = str(kind_cell or "").strip().lower()
                subject = subjectOf(subject_cell)
                course_line = line

                # Раздел «базовая математика»: курс идёт в линейку «ЕГЭ основной»
                # под отдельным предметом «Математика база»
                if line == "base":
                    course_line, subject = "ЕГЭ основной", "Математика база" if subject == "Математика" else subject

                # Не урок: нет дня/времени, прочерк, домашнее задание или неизвестный предмет
                if day is None or not time or time == "-" or kind == "домашка" or subject is None:
                    continue

                slot = slotOf(day, time)
                teacher = teacherName(teacher_cell)

                # «ДОП» — семинар: общий курс без потока в линейке семинаров
                if kind == "доп":
                    item = course(None, EXTRA_LINES[line if line in EXTRA_LINES else "ЕГЭ продвинутый"], subject)
                else:
                    item = course(stream, course_line, subject)

                if slot not in item["slots"]:
                    item["slots"].append(slot)

                # Семинары общие для потоков и встречаются на обоих листах: уроки считаем
                # отдельно по каждому потоку, а не объединение слотов. Внутри потока считаем
                # разные слоты, а не строки листа: один и тот же семинар может стоять на листе
                # и в блоке ЕГЭ, и в блоке «10 класс» — это один урок, а не два
                item.setdefault("per_stream", collections.defaultdict(set))[stream].add(tuple(slot) if slot else None)

                if teacher and teacher not in item["teachers"]:
                    item["teachers"].append(teacher)

    result = []

    # Недельные часы: у семинара — наибольшее число разных слотов в одном потоке,
    # у обычного курса — число его различных слотов
    for item in courses.values():
        per_stream = item.pop("per_stream", {})
        item["hours"] = max(map(len, per_stream.values())) if item["stream"] is None else len(item["slots"])
        result.append(item)

    return {
        "source": "Расписание и программы 26/27 (Google Sheets), streams 1 and 2",
        "day_grid": GRID,
        "streams": {str(stream): STARTS[stream] for stream in SHEETS},
        "extra_start": EXTRA_START,
        "courses": result,
    }


if __name__ == "__main__":
    data = parse(sys.argv[1])

    # Путь относительный: скрипт нужно запускать из корня проекта
    with open("tests/fixtures/school_26_27.json", "w", encoding="utf-8") as file:
        json.dump(data, file, indent=1, ensure_ascii=False)

    print(len(data["courses"]), "courses")
